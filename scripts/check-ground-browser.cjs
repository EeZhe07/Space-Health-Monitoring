const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
async function main() {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true })
    const crew = await context.newPage(), errors = []
    crew.on('pageerror', e => errors.push(e.message))
    const button = (page, name) => page.getByRole('button', { name, exact: true })
    await crew.goto('http://127.0.0.1:4173')
    await button(crew, 'Demo setup').click()
    await button(crew, 'Load team demonstration').click()
    await crew.getByRole('heading', { name: 'A teammate is needed', exact: true }).waitFor()
    const ground = await context.newPage()
    ground.on('pageerror', e => errors.push(e.message))
    await ground.goto('http://127.0.0.1:4173/#ground')
    await ground.getByRole('heading', { name: 'Ground Review', exact: true }).waitFor()
    const row = id => ground.locator('.crew-overview tbody tr').filter({ has: ground.getByRole('button', { name: id, exact: true }) })
    await row('CM-2').getByText('dizziness', { exact: true }).waitFor()
    assert.equal(await ground.locator('.crew-overview tbody tr').count(), 4)
    assert((await row('CM-4').innerText()).includes('No received report'))
    assert((await row('CM-1').innerText()).includes('No symptoms reported'))
    await crew.getByLabel('Demo crew profile').selectOption('CM-3')
    await crew.locator('.brand span').filter({ hasText: 'CM-3' }).waitFor()
    await button(crew, 'Self-check').click()
    await crew.getByRole('checkbox', { name: 'Headache', exact: true }).check()
    await button(crew, 'Save report and open handoff').click()
    await crew.getByRole('heading', { name: 'CM-3 · Episode summary', exact: true }).waitFor()
    assert(!(await row('CM-3').innerText()).includes('Headache'), 'Unshared local symptoms must not appear on ground')
    await button(crew, 'Share with demo ground').click()
    await row('CM-3').getByText('Headache', { exact: true }).waitFor()
    await button(crew, 'Today').click()
    const daily = crew.locator('.daily-check-in')
    await daily.getByRole('radio', { name: /^1 / }).check()
    await daily.getByRole('radio', { name: 'I feel uncomfortable', exact: true }).check()
    await button(crew, 'Save daily check-in').click()
    await crew.getByRole('heading', { name: 'Report how you feel', exact: true }).waitFor()
    await button(crew, 'Handoff · Pending').click()
    await button(crew, 'Share with demo ground').click()
    await button(ground, 'CM-3').click()
    await ground.getByText('Not shared. No mental-health conclusion can be drawn.', { exact: true }).waitFor()
    await crew.getByRole('checkbox', { name: 'Include my latest wellbeing summary in future shared reports', exact: true }).check()
    await button(crew, 'Share with demo ground').click()
    await ground.getByText(/1\/5 · Very low · Discomfort reported/).waitFor()
    await ground.getByLabel('Follow-up message').fill('Please share a fresh resting pulse and an update on the headache.')
    await button(ground, 'Request crew update').click()
    await crew.locator('.ground-response').getByText('Please share a fresh resting pulse and an update on the headache.', { exact: true }).waitFor()
    await button(crew, 'Today').click()
    await crew.locator('.crew-ground-notice').getByText('Please share a fresh resting pulse and an update on the headache.', { exact: true }).waitFor()
    await button(crew, 'Open ground request').click()
    await crew.getByRole('heading', { name: 'CM-3 · Episode summary', exact: true }).waitFor()
    await button(ground, 'Confirm snapshot viewed').click()
    await ground.locator('.ground-follow-up .report').filter({ hasText: 'Snapshot viewed' }).waitFor()
    assert((await row('CM-3').innerText()).includes('Update requested'), 'Viewing must not erase a request')
    await crew.getByLabel('Demo crew profile').selectOption('CM-2')
    await crew.locator('.brand span').filter({ hasText: 'CM-2' }).waitFor()
    await button(crew, 'Crew break').click()
    await crew.getByText('No mood saved for this replay.', { exact: true }).waitFor()
    await crew.getByLabel('Demo crew profile').selectOption('CM-3')
    await crew.locator('.brand span').filter({ hasText: 'CM-3' }).waitFor()
    await crew.locator('.daily-check-in').getByText(/Today’s report: 1\/5/).waitFor()
    await crew.getByLabel('Demo crew profile').selectOption('CM-4')
    await crew.locator('.brand span').filter({ hasText: 'CM-4' }).waitFor()
    await button(crew, 'Handoff · Pending').click()
    await button(crew, 'Share with demo ground').click()
    await ground.getByText('4 of 4 members have a received report', { exact: true }).waitFor()
    assert(!(await row('CM-4').innerText()).includes('No received report'))
    const download = ground.waitForEvent('download')
    await button(ground, 'Export crew summary (TXT)').click()
    const report = fs.readFileSync(await (await download).path(), 'utf8')
    for (const id of ['CM-1','CM-2','CM-3','CM-4']) assert(report.includes(id))
    assert(report.includes('Self-reported mood: 1/5'))
    await ground.evaluate(async () => { await navigator.serviceWorker.ready })
    await context.setOffline(true)
    await ground.reload()
    await ground.getByText('4 of 4 members have a received report', { exact: true }).waitFor()
    await button(ground, 'CM-3').click()
    await ground.getByText(/1\/5 · Very low · Discomfort reported/).waitFor()
    for (const width of [1440, 390]) {
      await ground.setViewportSize({ width, height: 1100 })
      assert(await ground.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      fs.mkdirSync('playwright-results', { recursive: true })
      await ground.screenshot({ path: 'playwright-results/ground-review-' + width + '.png', fullPage: true })
    }
    await crew.reload()
    await crew.locator('.brand span').filter({ hasText: 'CM-4' }).waitFor()
    await crew.getByLabel('Demo crew profile').selectOption('CM-3')
    await crew.locator('.brand span').filter({ hasText: 'CM-3' }).waitFor()
    await button(crew, 'Handoff · Pending').click()
    await crew.locator('.ground-response').getByText('Please share a fresh resting pulse and an update on the headache.', { exact: true }).waitFor()
    const oldBatch = await ground.getByLabel('Demo session', { exact: true }).locator('option').nth(1).getAttribute('value')
    await button(crew, 'Demo setup').click()
    await button(crew, 'Load team demonstration').click()
    await crew.locator('.brand span').filter({ hasText: 'CM-2' }).waitFor()
    await row('CM-4').getByText('No received report', { exact: true }).waitFor()
    assert(!(await row('CM-3').innerText()).includes('Headache'), 'A new demonstration must not inherit the older session')
    await ground.getByLabel('Demo session', { exact: true }).selectOption(oldBatch)
    await row('CM-3').getByText('Headache', { exact: true }).waitFor()
    assert.deepEqual(errors, [])
    console.log('PASS: four profiles, explicit sharing, whole-crew and individual analysis, missing report semantics, consent, linked acknowledgements/requests, two-tab updates, export, member isolation, offline/reload and responsive Ground Review.')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exit(1) })
