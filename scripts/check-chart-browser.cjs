const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

async function main() {
  fs.mkdirSync('playwright-results', { recursive: true })
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:4173')
    const clock = await page.locator('.clock strong').innerText()
    const slider = page.getByRole('slider', { name: 'Inspect heart rate history', exact: true })
    await slider.waitFor({ timeout: 5000 })
    const detail = page.getByRole('group', { name: 'Heart rate historical reading', exact: true })
    await slider.focus()
    await page.keyboard.press('Home')
    assert((await detail.innerText()).includes('71 bpm'))
    assert((await detail.innerText()).includes('13:30:00 UTC'))
    assert((await detail.innerText()).includes('13:30:05 UTC'))
    await page.keyboard.press('ArrowRight')
    assert((await detail.innerText()).includes('74 bpm'))
    await page.getByRole('button', { name: 'Previous reading', exact: true }).click()
    assert(await page.getByRole('button', { name: 'Previous reading', exact: true }).isDisabled())
    await page.getByRole('button', { name: 'Next reading', exact: true }).click()
    assert((await detail.innerText()).includes('74 bpm'))
    const lastPoint = await page.locator('.trend-chart .data-point').last().boundingBox()
    await page.mouse.move(lastPoint.x + lastPoint.width / 2, lastPoint.y + lastPoint.height / 2)
    assert((await detail.innerText()).includes('142 bpm'))
    const firstPoint = await page.locator('.trend-chart .data-point').first().boundingBox()
    await page.mouse.move(firstPoint.x + firstPoint.width / 2, firstPoint.y + firstPoint.height / 2)
    await page.mouse.move(5, 5)
    assert((await detail.innerText()).includes('71 bpm'), 'Selected details remain readable after leaving the plot')
    assert.equal(await page.locator('.clock strong').innerText(), clock, 'Inspection must not change the replay clock')
    await page.screenshot({ path: 'playwright-results/interactive-heart-rate.png', fullPage: true })
    await page.getByRole('button', { name: 'Measurements', exact: true }).click()
    for (const name of ['Heart rate', 'Blood oxygen', 'Breathing rate', 'Systolic blood pressure', 'Diastolic blood pressure', 'Body temperature', 'Sleep duration']) {
      await page.getByRole('button', { name: new RegExp('^' + name) }).click()
      await page.getByRole('group', { name: name + ' historical reading', exact: true }).waitFor()
      const input = page.getByRole('slider', { name: 'Inspect ' + name.toLowerCase() + ' history', exact: true })
      assert.equal(await input.count(), 1)
      assert((await page.getByRole('group', { name: name + ' historical reading', exact: true }).innerText()).includes('2027-07-18'))
    }
    if (!await page.getByRole('button', { name: 'Simulate multi-indicator changes', exact: true }).isVisible()) await page.getByText('Demo controls', { exact: false }).first().click()
    await page.getByRole('button', { name: 'Simulate multi-indicator changes', exact: true }).click()
    await page.getByRole('button', { name: /^Blood oxygen/ }).click()
    const oxygen = page.getByRole('slider', { name: 'Inspect blood oxygen history', exact: true })
    await oxygen.focus(); await page.keyboard.press('Home')
    assert((await page.getByRole('group', { name: 'Blood oxygen historical reading', exact: true }).innerText()).includes('98 %'))
    await page.keyboard.press('End')
    assert((await page.getByRole('group', { name: 'Blood oxygen historical reading', exact: true }).innerText()).includes('92 %'))
    await page.setViewportSize({ width: 390, height: 900 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.screenshot({ path: 'playwright-results/interactive-oxygen-mobile.png', fullPage: true })
    await page.getByRole('button', { name: /^Heart rate/ }).click()
    const replay = page.getByRole('slider', { name: 'Replay time', exact: true })
    await replay.focus(); await page.keyboard.press('Home')
    await page.getByText('No readings yet', { exact: true }).waitFor()
    await page.locator('input[aria-label="Replay time"]:not(:disabled)').waitFor()
    await replay.focus()
    await page.keyboard.press('ArrowRight')
    await page.waitForFunction(() => document.querySelector('.inspected-value')?.textContent.includes('71 bpm'))
    assert(!(await page.getByRole('group', { name: 'Heart rate historical reading', exact: true }).innerText()).includes('142 bpm'), 'Rewinding must not expose a selected future record')
    await page.locator('input[aria-label="Replay time"]:not(:disabled)').waitFor()
    await replay.focus(); await page.keyboard.press('End')
    await page.waitForFunction(() => document.querySelector('.inspected-value')?.textContent.includes('142 bpm'))
    await page.getByLabel('Load a separate scenario').selectOption('D')
    await page.getByRole('heading', { name: 'Crew status', exact: true }).waitFor()
    await page.getByText('No readings yet', { exact: true }).waitFor()
    assert.equal(await page.getByRole('slider', { name: 'Inspect heart rate history', exact: true }).count(), 0)
    assert.equal(await page.getByRole('group', { name: 'Heart rate historical reading', exact: true }).count(), 0)
    await page.getByLabel('Load a separate scenario').selectOption('A')
    await page.getByRole('slider', { name: 'Inspect heart rate history', exact: true }).waitFor()
    assert((await page.getByRole('group', { name: 'Heart rate historical reading', exact: true }).innerText()).includes('82 bpm'), 'A new replay must not retain the earlier selection')
    const touch = await browser.newContext({ viewport: { width: 390, height: 900 }, isMobile: true, hasTouch: true })
    const touchPage = await touch.newPage()
    await touchPage.goto('http://127.0.0.1:4173')
    await touchPage.locator('.trend-chart .data-point').first().tap()
    await touchPage.waitForFunction(() => document.querySelector('.inspected-value')?.textContent.includes('71 bpm'), undefined, { timeout: 5000 })
    assert((await touchPage.getByRole('group', { name: 'Heart rate historical reading', exact: true }).innerText()).includes('71 bpm'))
    assert.deepEqual(errors, [])
    console.log('PASS: hover/tap inspection, exact timestamps, keyboard and step controls, all seven indicator charts, selection reset, unchanged replay clock, empty state and phone overflow.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exit(1) })
