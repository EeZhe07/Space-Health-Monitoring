const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

async function main() {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 1000 }, acceptDownloads: true })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.clock.install({ time: new Date() })
    const button = name => page.getByRole('button', { name, exact: true })
    const card = page.locator('.daily-check-in')
    async function fill(rating, comfortable) {
      await card.getByRole('radio', { name: new RegExp('^' + rating + ' ') }).check()
      await card.getByRole('radio', { name: comfortable ? 'No uncomfortable feelings' : 'I feel uncomfortable', exact: true }).check()
      await button('Save daily check-in').click()
    }
    await page.goto('http://127.0.0.1:4173')
    await card.getByText('Check-in due', { exact: true }).waitFor()
    assert(await button('Save daily check-in').isDisabled())
    await fill(4, true)
    await card.getByText(/Today’s report: 4\/5/).waitFor()
    await page.reload()
    await card.getByText(/Today’s report: 4\/5/).waitFor()
    await page.evaluate(async () => {
      await navigator.serviceWorker.ready
      if (!navigator.serviceWorker.controller) await new Promise(resolve => navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true }))
    })
    await context.setOffline(true)
    await page.clock.fastForward(20 * 3600000 - 60000)
    assert.equal(await button('Save daily check-in').count(), 0)
    await page.clock.fastForward(60000)
    await card.getByText('Check-in due', { exact: true }).waitFor()
    await fill(1, false)
    await page.getByRole('heading', { name: 'Report how you feel', exact: true }).waitFor()
    await page.getByRole('status').filter({ hasText: 'Your daily answers are not copied' }).waitFor()
    assert.equal(await page.getByLabel('Anything a teammate should know?', { exact: false }).inputValue(), '')
    await page.getByRole('checkbox', { name: 'Dizziness', exact: true }).check()
    await button('Save report and open handoff').click()
    await page.getByRole('heading', { name: 'Onboard handoff', exact: true }).waitFor()
    const download = page.waitForEvent('download')
    await button('Export ground-review packet (JSON)').click()
    const packet = fs.readFileSync(await (await download).path(), 'utf8')
    assert(!packet.includes('moodRating') && !packet.includes('Daily self-check: mood') && !packet.includes('dailyCheckIns'))
    assert(packet.includes('Dizziness'))
    await button('Today').click()
    await page.getByText('Demo controls', { exact: false }).first().click()
    await button('Advance 20 hours · Daily reminder').click()
    await card.getByText('Check-in due', { exact: true }).waitFor()
    await fill(5, true)
    await card.getByText(/Today’s report: 5\/5/).waitFor()
    await page.getByRole('heading', { name: 'A teammate is needed', exact: true }).waitFor()
    await page.reload()
    await card.getByText(/Today’s report: 5\/5/).waitFor()
    await button('History').click()
    await page.getByText('Daily self-checks (3)', { exact: true }).click()
    await page.getByText('1/5 · Very low', { exact: true }).waitFor()
    await button('Today').click()
    await page.locator('.demo-controls>summary').click()
    await button('Advance 20 hours · Daily reminder').click()
    await card.getByText('Check-in due', { exact: true }).waitFor()
    for (const width of [1280, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      fs.mkdirSync('playwright-results', { recursive: true })
      await card.screenshot({ path: 'playwright-results/daily-check-' + width + '.png' })
    }
    assert.deepEqual(errors, [])
    console.log('PASS: required answers, 20-hour real and mission clocks, low-mood/discomfort routing, offline reload, history, preserved symptoms, privacy through symptom export and responsive quiz.')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exit(1) })
