const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

async function main() {
  fs.mkdirSync('playwright-results', { recursive: true })
  const browser = await chromium.launch({
    channel: 'chrome', headless: true,
  })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:4173')
  await page.getByRole('heading', { name: 'Crew status', exact: true }).waitFor()
  assert.equal(await page.getByText('Supporting references for ground review', { exact: true }).count(), 0)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: 'playwright-results/today-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Handoff · Pending', exact: true }).click()
  await page.getByLabel('Handoff findings', { exact: false }).fill('Reviewed the report; awaiting a fresh measurement.')
  await page.getByRole('button', { name: 'Acknowledge handoff', exact: true }).click()
  await page.getByRole('heading', { name: 'Handoff acknowledged', exact: true }).waitFor()
  await page.getByLabel('Update for ground review', { exact: true }).fill('Crew member remains under teammate observation.')
  await page.getByRole('button', { name: 'Save teammate update', exact: true }).click()
  await page.getByText('Crew member remains under teammate observation.', { exact: true }).waitFor()
  await page.reload()
  await page.getByRole('button', { name: 'Handoff', exact: true }).click()
  await page.getByRole('heading', { name: 'Handoff acknowledged', exact: true }).waitFor()
  assert(await page.getByText('dizziness', { exact: true }).count() > 0)
  await page.screenshot({ path: 'playwright-results/handoff-desktop.png', fullPage: true })
  await page.getByText('Demo controls', { exact: false }).first().click()
  await page.getByRole('button', { name: 'Reconnect sensor', exact: true }).click()
  await page.getByRole('button', { name: 'Self-check', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Dizziness', exact: true }).check()
  await page.screenshot({ path: 'playwright-results/self-check-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 900 })
  await page.screenshot({ path: 'playwright-results/self-check-mobile.png', fullPage: true })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByLabel('Record a heart rate already measured (bpm)').fill('83')
  await page.getByRole('button', { name: 'Save measurement', exact: true }).click()
  await page.getByText('83 bpm at', { exact: false }).first().waitFor()
  await page.getByRole('button', { name: 'Today', exact: true }).click()
  await page.getByText('Open concern', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export ground-review packet (JSON)', exact: true }).click()
  const download = await downloadPromise
  assert(download.suggestedFilename().endsWith('.json'))
  const packet = JSON.parse(fs.readFileSync(await download.path(), 'utf8'))
  assert.equal(packet.deliveryStatus, 'local_only')
  assert(packet.references.length > 0)
  assert(packet.timeline.some(event => event.description === 'Reviewed the report; awaiting a fresh measurement.'))
  assert(packet.timeline.some(event => event.type === 'handoff_note'))
  await page.getByLabel('Load a separate scenario').selectOption('A')
  await page.getByRole('heading', { name: 'Crew status', exact: true }).waitFor()
  await page.locator('.status-strip strong').filter({ hasText: /^82/ }).waitFor()
  await page.getByRole('button', { name: 'Self-check', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Dizziness', exact: true }).check()
  await page.getByLabel('Anything a teammate should know?', { exact: false }).fill('Dizzy after completing exercise')
  await page.getByRole('checkbox', { name: 'Headache', exact: true }).check()
  await page.getByRole('radio', { name: 'Not sure', exact: true }).check()
  await page.getByRole('button', { name: 'Save report and open handoff', exact: true }).click()
  await page.getByRole('heading', { name: 'Dizzy after completing exercise', exact: true }).first().waitFor()
  await page.getByText('Onset uncertain.', { exact: true }).first().waitFor()
  await page.getByRole('button', { name: 'Acknowledge handoff', exact: true }).click()
  await page.getByRole('heading', { name: 'Handoff acknowledged', exact: true }).waitFor()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  assert.equal(await page.getByText('Teammate took over', { exact: true }).count(), 1)
  await page.getByRole('button', { name: 'Measurements', exact: true }).click()
  await page.getByRole('heading', { name: 'Available measurements', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Simulate multi-indicator changes', exact: true }).click()
  await page.getByText('92 %', { exact: true }).waitFor()
  assert(await page.getByText('Review reading', { exact: true }).count() >= 3)
  await page.screenshot({ path: 'playwright-results/measurements-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Handoff', exact: true }).click()
  await page.getByRole('button', { name: 'Export ground-review packet (JSON)', exact: true }).waitFor()
  const multiDownloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export ground-review packet (JSON)', exact: true }).click()
  const multiPacket = JSON.parse(fs.readFileSync(await (await multiDownloadPromise).path(), 'utf8'))
  assert(multiPacket.observations.some(observation => observation.indicator === 'spo2'))
  assert(multiPacket.assessment.indicators.some(indicator => indicator.indicator === 'spo2' && indicator.state === 'review'))
  assert(multiPacket.references.some(reference => reference.url.includes('pulse-oximetry')))
  assert.equal(multiPacket.symptoms.length, 2)
  await page.getByLabel('Load a separate scenario').selectOption('D')
  await page.getByRole('heading', { name: 'Crew status', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Handoff · Pending', exact: true }).click()
  await page.getByRole('button', { name: 'Acknowledge handoff', exact: true }).click()
  await page.getByRole('heading', { name: 'Handoff acknowledged', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Today', exact: true }).click()
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    if (!navigator.serviceWorker.controller) {
      await new Promise(resolve => navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true }))
    }
  })
  await context.setOffline(true)
  await page.reload()
  await page.getByRole('heading', { name: 'Crew status', exact: true }).waitFor()
  await page.locator('.connection').filter({ hasText: 'Device offline' }).waitFor()
  assert.equal(await page.getByText('No measurement has been received in this scenario.', { exact: true }).count(), 1)
  for (const width of [768, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.screenshot({ path: 'playwright-results/today-' + width + '.png', fullPage: true })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal overflow at ' + width)
  }
  await page.close()
  const reopened = await context.newPage()
  await reopened.goto('http://127.0.0.1:4173')
  await reopened.getByRole('heading', { name: 'Crew status', exact: true }).waitFor()
  await reopened.getByRole('button', { name: 'Handoff', exact: true }).click()
  await reopened.getByRole('heading', { name: 'Handoff acknowledged', exact: true }).waitFor()
  assert.deepEqual(errors, [])
  await browser.close()
  console.log('PASS: handoff persistence, sensor restoration, manual input, symptom persistence, JSON export, scenario isolation, offline reload, offline reopen and responsive overflow.')
}
main().catch(error => { console.error(error); process.exit(1) })
